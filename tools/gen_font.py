#!/usr/bin/env python3
"""assets/fonts/m5x7.png (Daniel Linssen, CC0) -> odin/ui/font_gen.odin (bit rows and advances)."""
import os
import sys
from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, 'assets', 'fonts', 'm5x7.png')
OUT = os.path.join(ROOT, 'odin', 'ui', 'font_gen.odin')
CW, CH = 8, 9


def build():
    im = Image.open(SRC).convert('L')
    assert im.size == (128, 54), im.size
    lines = ['// Code generated by tools/gen_font.py from assets/fonts/m5x7.png. DO NOT EDIT.',
             '// m5x7 by Daniel Linssen (managore), CC0. ASCII 32..126; each row is a bitmask, bit 7 is the left pixel.',
             'package ui', '',
             'FONT_CELL_H :: %d' % CH, 'FONT_ASCENT :: 7 // rows above the baseline', '']
    rows, adv = [], []
    for i in range(95):
        cx, cy = (i % 16) * CW, (i // 16) * CH
        r = []
        maxx = -1
        for y in range(CH):
            v = 0
            for x in range(CW):
                if im.getpixel((cx + x, cy + y)) < 128:
                    v |= 0x80 >> x
                    maxx = max(maxx, x)
            r.append(v)
        rows.append(r)
        adv.append(5 if i == 0 else maxx + 2)  # space is 5; others ink width + 1 pixel
    lines.append('FONT_ROWS := [95][%d]u8{' % CH)
    for r in rows:
        lines.append('\t{' + ', '.join('0x%02x' % v for v in r) + '},')
    lines.append('}')
    lines.append('FONT_ADVANCE := [95]u8{' + ', '.join(str(a) for a in adv) + '}')
    return '\n'.join(lines) + '\n'


if __name__ == '__main__':
    text = build()
    if '--check' in sys.argv:
        ok = os.path.exists(OUT) and open(OUT).read() == text
        print('font up to date' if ok else 'STALE: run tools/gen_font.py')
        sys.exit(0 if ok else 1)
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    open(OUT, 'w', newline='\n').write(text)
    print('wrote', os.path.relpath(OUT, ROOT))
