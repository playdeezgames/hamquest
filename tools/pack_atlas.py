#!/usr/bin/env python3
"""Pack the sprite atlas and light profiles into odin/content/ (needs Pillow).

  tools/pack_atlas.py          write atlas.rgba and atlas_gen.odin
  tools/pack_atlas.py --check  fail if they are stale
"""
import math
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import atlas_layout  # noqa: E402
from PIL import Image  # noqa: E402

ROOT = os.path.dirname(HERE)
OUT = os.path.join(ROOT, 'odin', 'content')
PROFILE_LEN = 680   # covers the corner of the 480 px map pane from any player tile (<= 679)


def pascal(s):
    parts = re.split(r'[^A-Za-z0-9]+', s)
    out = ''.join(p[:1].upper() + p[1:] for p in parts if p)
    return ('N' + out) if (not out or out[0].isdigit()) else out


def name_of(path):
    return pascal(re.sub(r'\.png$', '', re.sub(r'^images/', '', path)))


def build():
    rects, height = atlas_layout.layout()
    atlas = Image.new('RGBA', (atlas_layout.ATLAS_WIDTH, height), (0, 0, 0, 0))
    base = os.path.dirname(atlas_layout.IMAGES)
    for rel, (x, y, w, h) in rects.items():
        im = Image.open(os.path.join(base, rel)).convert('RGBA')
        if im.size != (w, h):
            raise ValueError(rel)
        atlas.paste(im, (x, y))
    pixels = atlas.tobytes()

    # light radius masks are radially symmetric (checked within 2/255): keep one profile each
    lights = sorted(f for f in os.listdir(os.path.join(atlas_layout.IMAGES, 'lights')) if f.endswith('.png'))
    profiles = []
    k = math.sqrt(0.5)
    for f in lights:
        a = Image.open(os.path.join(atlas_layout.IMAGES, 'lights', f)).convert('RGBA').split()[3]
        prof = []
        for r in range(PROFILE_LEN):
            x = min(959, 480 + int(round(r * k)))
            y = min(959, 480 + int(round(r * k)))
            prof.append(a.getpixel((x, y)))
        profiles.append((os.path.splitext(f)[0], prof))

    L = ['// Code generated by tools/pack_atlas.py. DO NOT EDIT.', 'package content', '']
    L.append('ATLAS_W :: %d' % atlas.width)
    L.append('ATLAS_H :: %d' % atlas.height)
    L.append('ATLAS_PIXELS := #load("atlas.rgba") // RGBA8, row-major, ATLAS_W by ATLAS_H (a variable so it can be indexed)')
    L.append('LIGHT_PROFILE_LEN :: %d' % PROFILE_LEN)
    L.append('')
    L.append('IMAGE_RECTS := [Image_Id]Rect{')
    L.append('\t.None = {},')
    for rel in sorted(rects):
        x, y, w, h = rects[rel]
        L.append('\t.%s = {%d, %d, %d, %d},' % (name_of(rel), x, y, w, h))
    L.append('}')
    L.append('')
    L.append('// alpha of the darkness overlay (255 = black) by distance in pixels from the light')
    L.append('LIGHT_PROFILES := [Light_Radius][LIGHT_PROFILE_LEN]u8{')
    L.append('\t.None = {},')
    for name, prof in profiles:
        L.append('\t.Lights%s = {' % pascal(name))
        for i in range(0, PROFILE_LEN, 24):
            L.append('\t\t' + ', '.join(str(v) for v in prof[i:i + 24]) + ',')
        L.append('\t},')
    L.append('}')
    return pixels, '\n'.join(L) + '\n'


def main():
    pixels, odin = build()
    raw = os.path.join(OUT, 'atlas.rgba')
    gen = os.path.join(OUT, 'atlas_gen.odin')
    if '--check' in sys.argv:
        ok = os.path.exists(raw) and open(raw, 'rb').read() == pixels and os.path.exists(gen) and open(gen).read() == odin
        print('atlas up to date' if ok else 'STALE: run tools/pack_atlas.py')
        return 0 if ok else 1
    with open(raw, 'wb') as f:
        f.write(pixels)
    with open(gen, 'w', newline='\n') as f:
        f.write(odin)
    print('wrote atlas.rgba (%d bytes) and atlas_gen.odin' % len(pixels))
    return 0


if __name__ == '__main__':
    sys.exit(main())
